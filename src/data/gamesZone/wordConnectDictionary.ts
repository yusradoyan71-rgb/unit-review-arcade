export const WORD_CONNECT_DICTIONARY: ReadonlySet<string> = new Set<string>(WORD_LIST);

/**
 * Checks whether a candidate word is in the school-safe English dictionary.
 */
export function isValidDictionaryWord(word: string): boolean {
  if (!word || typeof word !== 'string') return false;
  const clean = word.trim().toUpperCase();
  if (clean.length < 3 || clean.length > 15) return false;
  return WORD_CONNECT_DICTIONARY.has(clean);
}

/**
 * Verifies that candidate word can be formed strictly from available letters,
 * respecting the exact available occurrence count of each letter.
 */
export function canFormFromLetters(word: string, availableLetters: string[]): boolean {
  if (!word || !availableLetters || availableLetters.length === 0) return false;
  const cleanWord = word.trim().toUpperCase();
  if (cleanWord.length === 0 || cleanWord.length > availableLetters.length) return false;

  const letterCounts: Record<string, number> = {};
  for (let i = 0; i < availableLetters.length; i++) {
    const char = availableLetters[i].toUpperCase();
    letterCounts[char] = (letterCounts[char] || 0) + 1;
  }

  for (let i = 0; i < cleanWord.length; i++) {
    const char = cleanWord[i];
    if (!letterCounts[char] || letterCounts[char] <= 0) {
      return false;
    }
    letterCounts[char]--;
  }

  return true;
}

/**
 * Finds all valid dictionary words formable from a set of available letters.
 */
export function findFormableWords(availableLetters: string[], minLength: number = 3): string[] {
  const results: string[] = [];
  const cleanLetters = availableLetters.map((l) => l.toUpperCase());

  for (const word of WORD_CONNECT_DICTIONARY) {
    if (word.length >= minLength && word.length <= cleanLetters.length) {
      if (canFormFromLetters(word, cleanLetters)) {
        results.push(word);
      }
    }
  }

  return results.sort((a, b) => a.length - b.length || a.localeCompare(b));
}
